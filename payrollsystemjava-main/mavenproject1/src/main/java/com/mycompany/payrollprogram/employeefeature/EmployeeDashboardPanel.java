    private void btnViewActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnViewActionPerformed
        int row = tblHistory.getSelectedRow();
        if (row < 0) {
            JOptionPane.showMessageDialog(this, "Select a payroll period to view its payslip.",
                    "No payslip selected", JOptionPane.INFORMATION_MESSAGE);
            return;
        }
        EmployeeMain main = findMain();
        if (main != null) {
            main.showPayslip(row);
        }
    }//GEN-LAST:event_btnViewActionPerformed

    private void btnPrintActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPrintActionPerformed
        int row = tblHistory.getSelectedRow();
        if (row < 0) {
            JOptionPane.showMessageDialog(this, "Select a payroll period to print its payslip.",
                    "No payslip selected", JOptionPane.INFORMATION_MESSAGE);
            return;
        }
        EmployeeMain main = findMain();
        if (main != null) {
            main.showPayslip(row);
            main.printPayslip();
        }
    }//GEN-LAST:event_btnPrintActionPerformed

    private EmployeeMain findMain() {
        java.awt.Window window = SwingUtilities.getWindowAncestor(this);
        return window instanceof EmployeeMain main ? main : null;
    }

    private void loadEmployee() {
        lblSubtitle.setText("Welcome, " + EmployeeData.FIRST_NAME + ". View your pay details and payslip history.");
        lblNameValue.setText(EmployeeData.NAME);
        lblIdValue.setText(EmployeeData.EMPLOYEE_ID);
        lblDepartmentValue.setText(EmployeeData.DEPARTMENT);
        lblNetAmount.setText("₱" + EmployeeData.money(EmployeeData.net(0)));
        lblNetPeriod.setText("Payroll period: " + EmployeeData.period(0));
        lblNetPayDate.setText("Pay date: " + EmployeeData.payDate(0));
    }

    private void loadHistory() {
        DefaultTableModel model = (DefaultTableModel) tblHistory.getModel();
        for (int i = 0; i < EmployeeData.count(); i++) {
            model.addRow(new Object[]{EmployeeData.period(i), EmployeeData.payDate(i),
                EmployeeData.money(EmployeeData.net(i)), EmployeeData.status(i)});
        }
        if (model.getRowCount() > 0) {
            tblHistory.setRowSelectionInterval(0, 0);
        }
    }

    private void styleTable() {
        tblHistory.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        tblHistory.setFont(new Font("Segoe UI", Font.PLAIN, 11));
        tblHistory.setRowHeight(42);
        tblHistory.setForeground(EmployeeMain.TEXT);
        tblHistory.setGridColor(new Color(235, 237, 242));
        tblHistory.setShowVerticalLines(false);
        tblHistory.getTableHeader().setFont(new Font("Segoe UI", Font.BOLD, 10));
        tblHistory.getTableHeader().setForeground(EmployeeMain.MUTED);
        tblHistory.getTableHeader().setBackground(new Color(247, 248, 251));
        tblHistory.getTableHeader().setPreferredSize(new Dimension(0, 32));
    }

