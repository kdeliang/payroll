    void showPayslip(int index) {
        lblSubtitle.setText(EmployeeData.period(index) + " · Your personal payroll record");
        lblName.setText(EmployeeData.NAME);
        lblMeta.setText(EmployeeData.EMPLOYEE_ID + " · " + EmployeeData.DEPARTMENT + " · " + EmployeeData.POSITION);
        lblPeriod.setText("Period: " + EmployeeData.range(index));
        lblPayDate.setText("Pay date: " + EmployeeData.payDate(index));

        JLabel[] earnings = {lblBasicValue, lblHonorariumValue, lblAllowancesValue, lblOvertimeValue};
        for (int i = 0; i < earnings.length; i++) {
            earnings[i].setText(EmployeeData.money(EmployeeData.amount(index, i)));
        }
        JLabel[] deductions = {lblSssValue, lblPagibigValue, lblPhilhealthValue, lblTaxValue,
            lblAbsencesValue, lblTardinessValue, lblLoansValue};
        for (int i = 0; i < deductions.length; i++) {
            deductions[i].setText(EmployeeData.money(EmployeeData.amount(index, 4 + i)));
        }
        lblGrossValue.setText("₱" + EmployeeData.money(EmployeeData.gross(index)));
        lblTotalValue.setText("₱" + EmployeeData.money(EmployeeData.deductions(index)));
        lblNetValue.setText("₱" + EmployeeData.money(EmployeeData.net(index)));
        lblStatus.setText("Status: " + EmployeeData.status(index) + " · Amounts in Philippine pesos (PHP)");
    }

    void printPayslip() {
        PrinterJob job = PrinterJob.getPrinterJob();
        job.setJobName("Payslip");
        job.setPrintable((graphics, pageFormat, pageIndex) -> {
            if (pageIndex > 0) {
                return Printable.NO_SUCH_PAGE;
            }
            Graphics2D g2 = (Graphics2D) graphics;
            g2.translate(pageFormat.getImageableX(), pageFormat.getImageableY());
            double scale = Math.min(1.0, pageFormat.getImageableWidth() / cardPayslip.getWidth());
            g2.scale(scale, scale);
            cardPayslip.printAll(g2);
            return Printable.PAGE_EXISTS;
        });
        if (job.printDialog()) {
            try {
                job.print();
            } catch (PrinterException exception) {
                JOptionPane.showMessageDialog(this, "Unable to print payslip: " + exception.getMessage(),
                        "Print error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }

