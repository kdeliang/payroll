    void showSection(String section) {
        ((CardLayout) pages.getLayout()).show(pages, section);
        JButton[] buttons = {btnDashboard, btnEmployees, btnAttendance, btnPayroll, btnPayslips};
        String[] sections = {"Dashboard", "Employees", "Attendance", "Payroll", "Payslips"};
        for (int i = 0; i < buttons.length; i++) {
            boolean selected = sections[i].equals(section);
            buttons[i].setBackground(selected ? PURPLE : NAVY);
            buttons[i].setForeground(selected ? Color.WHITE : new Color(218, 220, 228));
        }
    }

