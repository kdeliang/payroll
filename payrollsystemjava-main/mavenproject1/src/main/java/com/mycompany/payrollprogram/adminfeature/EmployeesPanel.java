    private void filter() {
        String text = txtSearch.getText().trim();
        sorter.setRowFilter(text.isEmpty() ? null : RowFilter.regexFilter("(?i)" + java.util.regex.Pattern.quote(text)));
    }

    private void loadSelectedEmployee() {
        int row = tblEmployees.convertRowIndexToModel(tblEmployees.getSelectedRow());
        for (int i = 0; i < fields.length; i++) {
            fields[i].setText(String.valueOf(tableModel.getValueAt(row, i)));
        }
    }

    private void saveEmployee() {
        String name = txtName.getText().trim();
        String id = txtId.getText().trim();
        String pay = txtPay.getText().trim();
        if (id.isEmpty() || name.isEmpty() || pay.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Employee ID, full name, and basic pay are required.",
                    "Missing information", JOptionPane.WARNING_MESSAGE);
            return;
        }
        try {
            Double.parseDouble(pay.replace(",", ""));
        } catch (NumberFormatException exception) {
            JOptionPane.showMessageDialog(this, "Enter a valid monthly basic pay amount.",
                    "Invalid pay", JOptionPane.WARNING_MESSAGE);
            return;
        }
        int selected = tblEmployees.getSelectedRow();
        Object[] values = {id, name, txtDepartment.getText().trim(), txtPosition.getText().trim(), pay, "Active"};
        if (selected >= 0) {
            int row = tblEmployees.convertRowIndexToModel(selected);
            for (int column = 0; column < values.length; column++) {
                tableModel.setValueAt(values[column], row, column);
            }
        } else {
            tableModel.addRow(values);
        }
        clearFields();
    }

    private void deactivateEmployee() {
        int selected = tblEmployees.getSelectedRow();
        if (selected < 0) {
            JOptionPane.showMessageDialog(this, "Select an employee to deactivate.",
                    "No employee selected", JOptionPane.INFORMATION_MESSAGE);
            return;
        }
        int row = tblEmployees.convertRowIndexToModel(selected);
        tableModel.setValueAt("Inactive", row, 5);
        clearFields();
    }

    private void clearFields() {
        tblEmployees.clearSelection();
        for (JTextField field : fields) {
            field.setText("");
        }
    }

