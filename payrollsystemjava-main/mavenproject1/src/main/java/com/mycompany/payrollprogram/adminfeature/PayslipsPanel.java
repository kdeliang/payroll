    private void showPreview(int row) {
        if (row < 0 || row >= tableModel.getRowCount()) {
            return;
        }
        String name = String.valueOf(tableModel.getValueAt(row, 0));
        String id = "EMP-00" + (row + 1);
        String net = String.valueOf(tableModel.getValueAt(row, 1));
        txaPreview.setText(name + "\n"
                + id + " · Payroll employee\n"
                + "Period: " + txtPeriod.getText() + "    Pay date: October 30, 2026\n"
                + "────────────────────────────────────────\n"
                + "Description                              Amount (PHP)\n\n"
                + "Basic pay                                   30,000.00\n"
                + "Honorarium                                    2,000.00\n"
                + "Allowances                                    1,500.00\n"
                + "Overtime                                        426.14\n"
                + "Gross pay                                    33,926.14\n"
                + "SSS / Pag-IBIG / PhilHealth                  2,450.00\n"
                + "Withholding tax                              1,471.98\n"
                + "Absences / tardiness                            42.61\n"
                + "Loans                                         1,000.00\n"
                + "Total deductions                             4,964.59\n"
                + "────────────────────────────────────────\n"
                + "NET PAY                                     ₱" + net);
        txaPreview.setCaretPosition(0);
    }

    private void printPayslip() {
        try {
            txaPreview.print();
        } catch (PrinterException exception) {
            JOptionPane.showMessageDialog(this, "Unable to print payslip: " + exception.getMessage(),
                    "Print error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void exportCsv() {
        StringBuilder csv = new StringBuilder("Employee,Net Pay (PHP)\n");
        for (int row = 0; row < tableModel.getRowCount(); row++) {
            csv.append('"').append(tableModel.getValueAt(row, 0)).append("\",")
                    .append(tableModel.getValueAt(row, 1)).append('\n');
        }
        javax.swing.JFileChooser chooser = new javax.swing.JFileChooser();
        chooser.setSelectedFile(new java.io.File("payroll-history.csv"));
        if (chooser.showSaveDialog(this) == javax.swing.JFileChooser.APPROVE_OPTION) {
            try (java.io.Writer writer = new java.io.OutputStreamWriter(
                    new java.io.FileOutputStream(chooser.getSelectedFile()), java.nio.charset.StandardCharsets.UTF_8)) {
                writer.write(csv.toString());
            } catch (java.io.IOException exception) {
                JOptionPane.showMessageDialog(this, "Unable to export payroll CSV: " + exception.getMessage(),
                        "Export error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }

