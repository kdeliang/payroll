    private static void paintPrompt(JTextField field, Graphics graphics, String prompt) {
        if (field.getDocument().getLength() == 0 && !field.hasFocus()) {
            Graphics2D promptGraphics = (Graphics2D) graphics.create();
            promptGraphics.setColor(new Color(139, 145, 164));
            promptGraphics.setFont(field.getFont());
            FontMetrics metrics = promptGraphics.getFontMetrics();
            Insets insets = field.getInsets();
            int baseline = (field.getHeight() - metrics.getHeight()) / 2 + metrics.getAscent();
            promptGraphics.drawString(prompt, insets.left + 1, baseline);
            promptGraphics.dispose();
        }
    }

    private static class PromptTextField extends JTextField {

        private final String prompt;

        private PromptTextField(String prompt) {
            this.prompt = prompt;
        }

        @Override
        protected void paintComponent(Graphics graphics) {
            super.paintComponent(graphics);
            paintPrompt(this, graphics, prompt);
        }
    }

    private static class PromptPasswordField extends JPasswordField {

        private final String prompt;

        private PromptPasswordField(String prompt) {
            this.prompt = prompt;
        }

        @Override
        protected void paintComponent(Graphics graphics) {
            super.paintComponent(graphics);
            paintPrompt(this, graphics, prompt);
        }
    }

