    private void saveAttendance() {
        if (txtEmployee.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Enter an employee name.", "Missing information",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }
        String[] values = {txtEmployee.getText().trim(), txtDaysWorked.getText().trim(),
            txtAbsentDays.getText().trim(), txtLateMinutes.getText().trim(), txtOvertimeHours.getText().trim()};
        try {
            for (int i = 1; i < values.length; i++) {
                if (Integer.parseInt(values[i]) < 0) {
                    throw new NumberFormatException();
                }
            }
        } catch (NumberFormatException exception) {
            JOptionPane.showMessageDialog(this, "Attendance totals must be non-negative whole numbers.",
                    "Invalid attendance", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int row = tblAttendance.getSelectedRow();
        if (row < 0) {
            tableModel.addRow(values);
        } else {
            for (int column = 0; column < values.length; column++) {
                tableModel.setValueAt(values[column], row, column);
            }
        }
        tblAttendance.clearSelection();
        JOptionPane.showMessageDialog(this, "Attendance record saved.", "Saved",
                JOptionPane.INFORMATION_MESSAGE);
    }

